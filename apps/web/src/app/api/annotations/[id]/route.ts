/**
 * GET  /api/annotations/[id]
 * PUT  /api/annotations/[id]
 *
 * Reviewer-facing surface for the annotation plan of a single screenshot: the
 * persisted set of overlays (highlight, arrow, badge, inset), the composed
 * per-step copy and the generated alt text. Produced by the annotation engine
 * on the worker during capture; this route lets a reviewer read the current
 * plan and edit it — with the acknowledgement that the actual image bytes are
 * not re-rendered by this route (that belongs to the export/render pipeline,
 * which re-renders the annotations from the plan when the guide is exported).
 *
 * Why editing annotations means editing the plan and not the pixels:
 *   - Re-rendering annotations onto a raster is a pure function of (image,
 *     plan). Keeping the plan authoritative means a reviewer's edits are
 *     portable across compression modes, aspect ratios and future re-captures
 *     of the underlying step.
 *   - Version history (a later phase) diffs the plan, not a binary blob.
 *   - The plan is small JSON, so a workspace-scoped artifact store is a fit.
 *
 * Contract:
 *   - Requires DATABASE_URL + SESSION_SECRET; returns 503 config_error
 *     otherwise (no annotation read/write without persistence).
 *   - Authenticates via the shared session module and asserts
 *     `PERMISSIONS.screenshot_update` for PUT (editing) and
 *     `PERMISSIONS.workspace_read` for GET. A caller without it gets 403
 *     from `toAuthzFailure`.
 *   - The `[id]` path segment is the screenshot id (UUID). The annotation
 *     plan is stored under `annotations/{screenshotId}.json` in the
 *     workspace-scoped object store.
 *   - GET returns `state: "pending"` with an empty plan when the annotation
 *     job has not yet written a plan, so the UI has something deterministic
 *     to poll; a truly missing screenshot is a 404.
 *   - PUT accepts a partial plan update: any of `overlays`, `stepCopy`,
 *     `altText`, `targetBox` (in that order they apply). Unknown fields are
 *     rejected with a 400 field path. The update is applied on top of the
 *     stored plan (not a replacement) so a caller can edit just the alt text
 *     without re-sending overlays.
 *   - PUT never touches the image bytes. The `version` field increments on
 *     every successful write so a GET after a PUT can distinguish "plan was
 *     edited" from "plan was untouched".
 *
 * What this route does NOT do:
 *   - Re-render the annotated image. The export pipeline owns rendering.
 *   - Re-run auto-annotation. That is triggered by the automation phase's
 *     re-capture job, not by an HTTP edit.
 *   - Expose an LLM endpoint. Alt text can be regenerated by the caller
 *     calling the annotation job again; this route stores what it is given.
 *
 * External setup the operator must supply for the annotation job to have run
 * in the first place (documented; this route does not degrade silently):
 *   - Nothing for annotation itself — overlays are composed from element
 *     geometry the capture phase already stored.
 *   - An LLM provider (hosted provider key or a local Ollama/vLLM base URL)
 *     for AI-sourced step copy and alt text. Without one, the worker uses
 *     the deterministic composer in `packages/annotate/src/*` and the plan
 *     records `source: "composed"` on each item.
 */

