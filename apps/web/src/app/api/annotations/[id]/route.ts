const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Workspace-relative storage key prefix for annotation plans. The workspace
 * scoping is applied by `forWorkspace()`, so the key here has no workspace id.
 */
const ANNOTATIONS_PREFIX = "annotations";

/** Cap on overlays in a single plan; matches the annotation engine's limit. */
const MAX_OVERLAYS = 64;
/** Cap on alt-text length accepted in an edit (matches the annotate module). */
const MAX_ALT_TEXT_LENGTH = 220;
/** Cap on a step-copy instruction accepted in an edit. */
const MAX_INSTRUCTION_LENGTH = 1000;
/** Cap on a step title accepted in an edit. */
const MAX_STEP_TITLE_LENGTH = 200;

/** Roles accepted by the overlay validator; matches `OverlayDescriptor`. */
const VALID_OVERLAY_KINDS = ["highlight", "arrow", "badge", "inset"] as const;
type OverlayKind = (typeof VALID_OVERLAY_KINDS)[number];

/* -------------------------------------------------------------------------- */
/* Persisted plan shape                                                        */
/* -------------------------------------------------------------------------- */

/**
 * A minimal, forward-compatible shape. Unknown fields written by the worker
 * are preserved on a round-trip read/write — a PUT merges into the existing
 * plan, so it never drops worker fields it does not know about.
 */
interface PersistedOverlay {
  readonly kind?: unknown;
  readonly stepNumber?: unknown;
  readonly insetCaption?: unknown;
  readonly box?: unknown;
  readonly [key: string]: unknown;
}

interface PersistedStepCopy {
  readonly instruction?: unknown;
  readonly stepTitle?: unknown;
  readonly source?: unknown;
  readonly [key: string]: unknown;
}

interface PersistedAltText {
  readonly altText?: unknown;
  readonly source?: unknown;
  readonly degraded?: unknown;
  readonly reason?: unknown;
  readonly [key: string]: unknown;
}

interface PersistedTargetBox {
  readonly x?: unknown;
  readonly y?: unknown;
  readonly width?: unknown;
  readonly height?: unknown;
  readonly [key: string]: unknown;
}

interface PersistedAnnotationPlan {
  readonly kind?: unknown;
  readonly workspaceId?: unknown;
  readonly screenshotId?: unknown;
  readonly version?: unknown;
  readonly overlays?: unknown;
  readonly stepCopy?: unknown;
  readonly altText?: unknown;
  readonly targetBox?: unknown;
  /** ISO timestamp of the last write. */
  readonly updatedAt?: unknown;
  readonly updatedBy?: unknown;
  readonly [key: string]: unknown;
}

