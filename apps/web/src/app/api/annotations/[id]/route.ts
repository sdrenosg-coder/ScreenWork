/* -------------------------------------------------------------------------- */
/* Storage helpers                                                             */
/* -------------------------------------------------------------------------- */

function annotationKey(screenshotId: string): string {
  return `${ANNOTATIONS_PREFIX}/${screenshotId}.json`;
}

type StoreLike = {
  readonly get: (key: string) => Promise<Buffer | null>;
  readonly put: (
    key: string,
    data: Buffer,
    opts?: {
      readonly contentType?: string;
      readonly contentLength?: number;
      readonly metadata?: Readonly<Record<string, string>>;
    },
  ) => Promise<void>;
};

type ReadOutcome =
  | { readonly kind: "ok"; readonly plan: PersistedAnnotationPlan }
  | { readonly kind: "not-found" }
  | { readonly kind: "corrupt" };

async function readPlan(
  store: StoreLike,
  screenshotId: string,
): Promise<ReadOutcome> {
  const key = annotationKey(screenshotId);
  let bytes: Buffer | null;
  try {
    bytes = await store.get(key);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (/not.?found|enoent|no such key|404/i.test(message)) {
      return { kind: "not-found" };
    }
    throw error;
  }
  if (bytes === null) return { kind: "not-found" };
  let parsed: unknown;
  try {
    parsed = JSON.parse(bytes.toString("utf8"));
  } catch {
    return { kind: "corrupt" };
  }
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    return { kind: "corrupt" };
  }
  return { kind: "ok", plan: parsed as PersistedAnnotationPlan };
}

/* -------------------------------------------------------------------------- */
/* Normalisation (read path)                                                   */
/* -------------------------------------------------------------------------- */

function asString(value: unknown): string | null {
  return typeof value === "string" && value.length > 0 ? value : null;
}

function asNumber(value: unknown): number | null {
  if (typeof value === "number" && Number.isFinite(value)) return value;
  if (typeof value === "string") {
    const n = Number(value);
    if (Number.isFinite(n)) return n;
  }
  return null;
}

function asRecord(value: unknown): Readonly<Record<string, unknown>> {
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    return value as Readonly<Record<string, unknown>>;
  }
  return {};
}

function asBoolean(value: unknown): boolean {
  return value === true;
}

function isOverlayKind(value: unknown): value is OverlayKind {
  return (
    typeof value === "string" &&
    (VALID_OVERLAY_KINDS as readonly string[]).includes(value)
  );
}

function normaliseBox(raw: unknown): BoxDto | null {
  const obj = asRecord(raw);
  const x = asNumber(obj["x"]);
  const y = asNumber(obj["y"]);
  const width = asNumber(obj["width"]);
  const height = asNumber(obj["height"]);
  if (x === null || y === null || width === null || height === null) return null;
  if (width <= 0 || height <= 0) return null;
  return { x, y, width, height };
}

function normaliseOverlay(raw: unknown): OverlayDto | null {
  const obj = asRecord(raw);
  if (!isOverlayKind(obj["kind"])) return null;
  const stepNumberRaw = asNumber(obj["stepNumber"]);
  const stepNumber =
    stepNumberRaw !== null && stepNumberRaw >= 1 && Number.isInteger(stepNumberRaw)
      ? stepNumberRaw
      : null;
  const insetCaption = asString(obj["insetCaption"]);
  const box = normaliseBox(obj["box"]);
  return {
    kind: obj["kind"],
    stepNumber,
    insetCaption,
    box,
  };
}

function normaliseStepCopy(raw: unknown): StepCopyDto | null {
  if (raw === null || raw === undefined) return null;
  const obj = asRecord(raw);
  const instruction = asString(obj["instruction"]);
  if (instruction === null) return null;
  return {
    instruction,
    stepTitle: asString(obj["stepTitle"]),
    source: asString(obj["source"]),
  };
}

function normaliseAltText(raw: unknown): AltTextDto | null {
  if (raw === null || raw === undefined) return null;
  const obj = asRecord(raw);
  const altText = asString(obj["altText"]);
  if (altText === null) return null;
  return {
    altText,
    source: asString(obj["source"]),
    degraded: asBoolean(obj["degraded"]),
    reason: asString(obj["reason"]),
  };
}

function normaliseVersion(raw: unknown): number {
  const n = asNumber(raw);
  if (n === null || !Number.isInteger(n) || n < 0) return 0;
  return n;
}

function normaliseIsoTimestamp(raw: unknown): string | null {
  if (raw instanceof Date) return raw.toISOString();
  if (typeof raw === "string") {
    const d = new Date(raw);
    if (!Number.isNaN(d.getTime())) return d.toISOString();
    return raw;
  }
  return null;
}

function buildAnnotationDto(plan: PersistedAnnotationPlan): AnnotationDto {
  const rawOverlays = Array.isArray(plan.overlays)
    ? (plan.overlays as readonly unknown[])
    : [];
  const overlays: OverlayDto[] = [];
  for (let i = 0; i < rawOverlays.length && overlays.length < MAX_OVERLAYS; i += 1) {
    const n = normaliseOverlay(rawOverlays[i]);
    if (n !== null) overlays.push(n);
  }
  return {
    overlays,
    stepCopy: normaliseStepCopy(plan.stepCopy),
    altText: normaliseAltText(plan.altText),
    targetBox: normaliseBox(plan.targetBox),
  };
}

/* -------------------------------------------------------------------------- */
/* PUT body parsing                                                            */
/* -------------------------------------------------------------------------- */

interface ValidatedPutBody {
  readonly overlays?: readonly PersistedOverlay[];
  readonly stepCopy?: PersistedStepCopy;
  readonly altText?: PersistedAltText;
  readonly targetBox?: PersistedTargetBox;
}

function validatePutBody(raw: unknown): ValidatedPutBody | NextResponse {
  if (raw === null || raw === undefined) {
    return NextResponse.json(
      {
        error: "invalid_json",
        message:
          "PUT requires a JSON body with at least one of: overlays, stepCopy, altText, targetBox.",
      },
      { status: 400 },
    );
  }
  if (typeof raw !== "object" || Array.isArray(raw)) {
    return NextResponse.json(
      { error: "invalid_json", message: "Request body must be a JSON object." },
      { status: 400 },
    );
  }
  const body = raw as Record<string, unknown>;
  const allowed = new Set(["overlays", "stepCopy", "altText", "targetBox"]);
  for (const key of Object.keys(body)) {
    if (!allowed.has(key)) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: key,
          message: `Unknown field "${key}". Allowed fields: overlays, stepCopy, altText, targetBox.`,
        },
        { status: 400 },
      );
    }
  }
  if (Object.keys(body).length === 0) {
    return NextResponse.json(
      {
        error: "validation_error",
        field: "(body)",
        message:
          "PUT body is empty. Supply at least one of overlays, stepCopy, altText, targetBox.",
      },
      { status: 400 },
    );
  }

  const out: {
    overlays?: PersistedOverlay[];
    stepCopy?: PersistedStepCopy;
    altText?: PersistedAltText;
    targetBox?: PersistedTargetBox;
  } = {};

  // ------------------------------------------------------------ overlays --
  if (Object.prototype.hasOwnProperty.call(body, "overlays")) {
    const raw2 = body["overlays"];
    if (!Array.isArray(raw2)) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "overlays",
          message: "overlays must be an array of overlay objects.",
        },
        { status: 400 },
      );
    }
    if (raw2.length > MAX_OVERLAYS) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "overlays",
          message: `At most ${MAX_OVERLAYS} overlays per plan.`,
        },
        { status: 400 },
      );
    }
    const overlays: PersistedOverlay[] = [];
    for (let i = 0; i < raw2.length; i += 1) {
      const entry = raw2[i];
      if (entry === null || typeof entry !== "object" || Array.isArray(entry)) {
        return NextResponse.json(
          {
            error: "validation_error",
            field: `overlays[${i}]`,
            message: "Each overlay must be an object.",
          },
          { status: 400 },
        );
      }
      const obj = entry as Record<string, unknown>;
      if (!isOverlayKind(obj["kind"])) {
        return NextResponse.json(
          {
            error: "validation_error",
            field: `overlays[${i}].kind`,
            message: `kind must be one of: ${VALID_OVERLAY_KINDS.join(", ")}.`,
          },
          { status: 400 },
        );
      }
      // Every other field is passed through as-is; the plan is versioned
      // alongside the image, so unknown keys are preserved for the renderer.
      // Validate only what the read path exposes with a strict contract.
      if (Object.prototype.hasOwnProperty.call(obj, "stepNumber")) {
        const sn = obj["stepNumber"];
        if (
          sn !== null &&
          (typeof sn !== "number" || !Number.isInteger(sn) || sn < 1)
        ) {
          return NextResponse.json(
            {
              error: "validation_error",
              field: `overlays[${i}].stepNumber`,
              message: "stepNumber must be a positive integer or null.",
            },
            { status: 400 },
          );
        }
      }
      if (Object.prototype.hasOwnProperty.call(obj, "insetCaption")) {
        const cap = obj["insetCaption"];
        if (cap !== null && typeof cap !== "string") {
          return NextResponse.json(
            {
              error: "validation_error",
              field: `overlays[${i}].insetCaption`,
              message: "insetCaption must be a string or null.",
            },
            { status: 400 },
          );
        }
      }
      if (Object.prototype.hasOwnProperty.call(obj, "box")) {
        const boxValue = obj["box"];
        if (boxValue !== null) {
          const boxErr = validateBox(rawBoxOrThrow(boxValue));
          if (boxErr !== null) {
            return NextResponse.json(
              {
                error: "validation_error",
                field: `overlays[${i}].box.${boxErr.field}`,
                message: boxErr.message,
              },
              { status: 400 },
            );
          }
        }
      }
      overlays.push(obj as PersistedOverlay);
    }
    out.overlays = overlays;
  }

  // ------------------------------------------------------------ stepCopy --
  if (Object.prototype.hasOwnProperty.call(body, "stepCopy")) {
    const raw2 = body["stepCopy"];
    if (raw2 === null) {
      // A caller can explicitly clear stepCopy by sending null; treat that
      // as "remove the stepCopy from the plan" — the read path returns null.
      return NextResponse.json(
        {
          error: "validation_error",
          field: "stepCopy",
          message:
            "stepCopy cannot be null on this endpoint. Supply the fields you want to change (instruction is required).",
        },
        { status: 400 },
      );
    }
    if (typeof raw2 !== "object" || Array.isArray(raw2)) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "stepCopy",
          message: "stepCopy must be an object.",
        },
        { status: 400 },
      );
    }
    const obj = raw2 as Record<string, unknown>;
    const instruction = obj["instruction"];
    if (typeof instruction !== "string" || instruction.trim().length === 0) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "stepCopy.instruction",
          message: "stepCopy.instruction must be a non-empty string.",
        },
        { status: 400 },
      );
    }
    if (instruction.length > MAX_INSTRUCTION_LENGTH) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "stepCopy.instruction",
          message: `instruction exceeds the ${MAX_INSTRUCTION_LENGTH}-character limit.`,
        },
        { status: 400 },
      );
    }
    let stepTitle: string | null = null;
    if (Object.prototype.hasOwnProperty.call(obj, "stepTitle")) {
      const t = obj["stepTitle"];
      if (t === null) {
        stepTitle = null;
      } else if (typeof t === "string") {
        if (t.length > MAX_STEP_TITLE_LENGTH) {
          return NextResponse.json(
            {
              error: "validation_error",
              field: "stepCopy.stepTitle",
              message: `stepTitle exceeds the ${MAX_STEP_TITLE_LENGTH}-character limit.`,
            },
            { status: 400 },
          );
        }
        stepTitle = t;
      } else {
        return NextResponse.json(
          {
            error: "validation_error",
            field: "stepCopy.stepTitle",
            message: "stepCopy.stepTitle must be a string or null.",
          },
          { status: 400 },
        );
      }
    }
    out.stepCopy = {
      ...obj,
      instruction,
      stepTitle,
      // A human edit is authoritative; record it as such so provenance shows
      // a reviewer touched this stepCopy, not the LLM.
      source: "reviewer",
    };
  }

  // ------------------------------------------------------------- altText --
  if (Object.prototype.hasOwnProperty.call(body, "altText")) {
    const raw2 = body["altText"];
    if (typeof raw2 !== "object" || raw2 === null || Array.isArray(raw2)) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "altText",
          message: "altText must be an object.",
        },
        { status: 400 },
      );
    }
    const obj = raw2 as Record<string, unknown>;
    const altText = obj["altText"];
    if (typeof altText !== "string" || altText.trim().length === 0) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "altText.altText",
          message: "altText.altText must be a non-empty string.",
        },
        { status: 400 },
      );
    }
    if (altText.length > MAX_ALT_TEXT_LENGTH) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "altText.altText",
          message: `altText exceeds the ${MAX_ALT_TEXT_LENGTH}-character limit.`,
        },
        { status: 400 },
      );
    }
    let reason: string | null = null;
    if (Object.prototype.hasOwnProperty.call(obj, "reason")) {
      const r = obj["reason"];
      if (r !== null && typeof r !== "string") {
        return NextResponse.json(
          {
            error: "validation_error",
            field: "altText.reason",
            message: "altText.reason must be a string or null.",
          },
          { status: 400 },
        );
      }
      reason = r;
    }
    out.altText = {
      ...obj,
      altText: altText.trim(),
      source: "reviewer",
      reason,
    };
  }

  // ----------------------------------------------------------- targetBox --
  if (Object.prototype.hasOwnProperty.call(body, "targetBox")) {
    const raw2 = body["targetBox"];
    if (raw2 === null) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "targetBox",
          message:
            "targetBox cannot be cleared through this endpoint; it is required to render overlays and comes from the automation phase.",
        },
        { status: 400 },
      );
    }
    if (typeof raw2 !== "object" || Array.isArray(raw2)) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: "targetBox",
          message: "targetBox must be an object { x, y, width, height }.",
        },
        { status: 400 },
      );
    }
    const obj = raw2 as Record<string, unknown>;
    const err = validateBox(obj);
    if (err !== null) {
      return NextResponse.json(
        {
          error: "validation_error",
          field: `targetBox.${err.field}`,
          message: err.message,
        },
        { status: 400 },
      );
    }
    out.targetBox = obj as PersistedTargetBox;
  }

  return out;
}

function rawBoxOrThrow(value: unknown): Record<string, unknown> {
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    return value as Record<string, unknown>;
  }
  return {};
}

function validateBox(
  obj: Readonly<Record<string, unknown>>,
): { readonly field: string; readonly message: string } | null {
  const x = obj["x"];
  const y = obj["y"];
  const width = obj["width"];
  const height = obj["height"];
  if (typeof x !== "number" || !Number.isFinite(x)) {
    return { field: "x", message: "x must be a finite number." };
  }
  if (typeof y !== "number" || !Number.isFinite(y)) {
    return { field: "y", message: "y must be a finite number." };
  }
  if (typeof width !== "number" || !Number.isFinite(width) || width <= 0) {
    return { field: "width", message: "width must be a finite positive number." };
  }
  if (typeof height !== "number" || !Number.isFinite(height) || height <= 0) {
    return {
      field: "height",
      message: "height must be a finite positive number.",
    };
  }
  if (x < 0 || y < 0) {
    return {
      field: "x",
      message: "x and y must be non-negative (image-space pixel coordinates).",
    };
  }
  return null;
}

/* -------------------------------------------------------------------------- */
/* Response message notes                                                      */
/* -------------------------------------------------------------------------- */

function buildNotes(plan: PersistedAnnotationPlan | null): readonly string[] {
  const notes: string[] = [];
  if (plan === null) {
    notes.push(
      "No annotation plan exists yet for this screenshot. It will appear once the annotation job has run.",
    );
    return notes;
  }
  const altText = normaliseAltText(plan.altText);
  if (altText !== null && altText.degraded) {
    notes.push(
      "The alt text is marked degraded: the target element was identified by role only because no accessible name was available at capture time. Consider replacing it with a human-written description.",
    );
  }
  const overlays = Array.isArray(plan.overlays) ? plan.overlays : [];
  if (overlays.length === 0) {
    notes.push(
      "No overlays are recorded for this screenshot; the capture ran without annotations or the annotation engine deferred to a later pass.",
    );
  }
  const stepCopy = normaliseStepCopy(plan.stepCopy);
  if (stepCopy === null) {
    notes.push(
      "No step copy is recorded. Generate step copy (see `packages/annotate/src/stepCopy.ts`) before finalising the guide.",
    );
  }
  return notes;
}

/* -------------------------------------------------------------------------- */
/* Route: GET                                                                  */
/* -------------------------------------------------------------------------- */

export async function GET(
  req: Request,
  context: { readonly params: { readonly id: string } },
): Promise<NextResponse> {
  const config = getConfig();

  if (!config.database.configured) {
    return NextResponse.json(
      {
        error: "config_error",
        message:
          "DATABASE_URL is not configured on this server. Annotation plans cannot be read.",
      },
      { status: 503 },
    );
  }
  if (!config.auth.sessionSecretConfigured) {
    return NextResponse.json(
      {
        error: "config_error",
        message: "SESSION_SECRET is not configured on this server.",
      },
      { status: 503 },
    );
  }

  const session = await loadSessionAndAuthorize(req, PERMISSIONS.workspace_read, "GET");
  if (session instanceof NextResponse) return session;
  const workspaceId = session.activeWorkspaceId;
  if (workspaceId === null) {
    return NextResponse.json(
      {
        error: "workspace_required",
        message: "An active workspace is required to read an annotation plan.",
      },
      { status: 403 },
    );
  }

  const screenshotId = context.params.id;
  if (typeof screenshotId !== "string" || !UUID_PATTERN.test(screenshotId)) {
    return NextResponse.json(
      {
        error: "validation_error",
        field: "id",
        message: "Screenshot id must be a UUID.",
      },
      { status: 400 },
    );
  }

  const store = await openStoreOrError(workspaceId, "GET");
  if (store instanceof NextResponse) return store;

  let outcome: ReadOutcome;
  try {
    outcome = await readPlan(store, screenshotId);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(
      `[/api/annotations/[id]] storage read failed for ${screenshotId}: ${message}\n`,
    );
    return NextResponse.json(
      {
        error: "storage_failed",
        message:
          "The annotation plan could not be read from the object store. Check server logs.",
      },
      { status: 503 },
    );
  }

  if (outcome.kind === "corrupt") {
    return NextResponse.json(
      {
        error: "corrupt_artifact",
        message:
          "The annotation plan is not a valid JSON object. It may have been written by an incompatible deployment; re-run the annotation job.",
      },
      { status: 500 },
    );
  }

  if (outcome.kind === "not-found") {
    // Distinguish "screenshot exists but no plan yet" from "no such
    // screenshot". We only check the file key's sidecar JSON rather than the
    // image, because writing an empty placeholder here would mask a genuine
    // absence. A caller who needs the image existence check should hit the
    // screenshot route.
    const emptyPlan: PersistedAnnotationPlan = {
      kind: "annotation-plan",
      workspaceId,
      screenshotId,
      version: 0,
      overlays: [],
      updatedAt: null,
    };
    const response: AnnotationResponse = {
      screenshotId,
      workspaceId,
      state: "pending",
      version: 0,
      annotation: buildAnnotationDto(emptyPlan),
      updatedAt: null,
      updatedBy: null,
      message:
        "No annotation plan has been recorded for this screenshot yet. It will appear once the annotation job has run.",
      notes: buildNotes(null),
    };
    return NextResponse.json(response, { status: 200 });
  }

  const plan = outcome.plan;

  // Defence in depth: refuse to serve a plan whose embedded workspaceId
  // disagrees with the caller's active workspace. A mismatch means a bug
  // elsewhere; surfacing 404 is safer than returning the wrong data.
  const persistedWorkspaceId = asString(plan.workspaceId);
  if (persistedWorkspaceId !== null && persistedWorkspaceId !== workspaceId) {
    process.stderr.write(
      `[/api/annotations/[id]] workspace mismatch for ${screenshotId}: stored=${persistedWorkspaceId} caller=${workspaceId}\n`,
    );
    return NextResponse.json(
      {
        error: "not_found",
        message:
          "No annotation plan exists under this id in your active workspace.",
      },
      { status: 404 },
    );
  }

  const version = normaliseVersion(plan.version);
  const updatedAt = normaliseIsoTimestamp(plan.updatedAt);
  const updatedBy = asString(plan.updatedBy);
  const annotation = buildAnnotationDto(plan);

  const state: AnnotationStateDto = "ready";
  const message = (() => {
    if (annotation.overlays.length === 0 && annotation.stepCopy === null) {
      return "The annotation plan exists but is empty: no overlays and no step copy have been recorded.";
    }
    return `Annotation plan version ${version} with ${annotation.overlays.length} overlay(s).`;
  })();

  const response: AnnotationResponse = {
    screenshotId,
    workspaceId,
    state,
    version,
    annotation,
    updatedAt,
    updatedBy,
    message,
    notes: buildNotes(plan),
  };
  return NextResponse.json(response, { status: 200 });
}

/* -------------------------------------------------------------------------- */
/* Route: PUT                                                                  */
/* -------------------------------------------------------------------------- */

export async function PUT(
  req: Request,
  context: { readonly params: { readonly id: string } },
): Promise<NextResponse> {
  const config = getConfig();

  if (!config.database.configured) {
    return NextResponse.json(
      {
        error: "config_error",
        message:
          "DATABASE_URL is not configured on this server. Annotation plans cannot be edited.",
      },
      { status: 503 },
    );
  }
  if (!config.auth.sessionSecretConfigured) {
    return NextResponse.json(
      {
        error: "config_error",
        message: "SESSION_SECRET is not configured on this server.",
      },
      { status: 503 },
    );
  }

  const session = await loadSessionAndAuthorize(req, PERMISSIONS.screenshot_update, "PUT");
  if (session instanceof NextResponse) return session;
  const workspaceId = session.activeWorkspaceId;
  if (workspaceId === null) {
    return NextResponse.json(
      {
        error: "workspace_required",
        message: "An active workspace is required to edit an annotation plan.",
      },
      { status: 403 },
    );
  }

  const screenshotId = context.params.id;
  if (typeof screenshotId !== "string" || !UUID_PATTERN.test(screenshotId)) {
    return NextResponse.json(
      {
        error: "validation_error",
        field: "id",
        message: "Screenshot id must be a UUID.",
      },
      { status: 400 },
    );
  }

  // ------------------------------------------------------------- body ------
  let bodyJson: unknown;
  try {
    bodyJson = await req.json();
  } catch {
    return NextResponse.json(
      { error: "invalid_json", message: "Request body must be valid JSON." },
      { status: 400 },
    );
  }
  const validated = validatePutBody(bodyJson);
  if (validated instanceof NextResponse) return validated;

  // ------------------------------------------------------------ storage ----
  const store = await openStoreOrError(workspaceId, "PUT");
  if (store instanceof NextResponse) return store;

  // Read the existing plan so we can merge. A missing plan is fine — this
  // becomes a create-with-version-1.
  let existing: PersistedAnnotationPlan | null = null;
  try {
    const outcome = await readPlan(store, screenshotId);
    if (outcome.kind === "ok") {
      existing = outcome.plan;
    } else if (outcome.kind === "corrupt") {
      return NextResponse.json(
        {
          error: "corrupt_artifact",
          message:
            "The existing annotation plan is not a valid JSON object. Re-run the annotation job before editing; this route refuses to overwrite an unreadable plan.",
        },
        { status: 500 },
      );
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(
      `[/api/annotations/[id]] storage read (pre-update) failed for ${screenshotId}: ${message}\n`,
    );
    return NextResponse.json(
      {
        error: "storage_failed",
        message:
          "The existing annotation plan could not be read. Check server logs.",
      },
      { status: 503 },
    );
  }

  // Defence in depth: match the workspace embedded in the plan.
  if (existing !== null) {
    const persistedWorkspaceId = asString(existing.workspaceId);
    if (persistedWorkspaceId !== null && persistedWorkspaceId !== workspaceId) {
      process.stderr.write(
        `[/api/annotations/[id]] PUT workspace mismatch for ${screenshotId}: stored=${persistedWorkspaceId} caller=${workspaceId}\n`,
      );
      return NextResponse.json(
        {
          error: "not_found",
          message:
            "No annotation plan exists under this id in your active workspace.",
        },
        { status: 404 },
      );
    }
  }

  // ------------------------------------------------------------- merge -----
  const nowIso = new Date().toISOString();
  const previousVersion = existing !== null ? normaliseVersion(existing.version) : 0;
  const nextVersion = previousVersion + 1;

  // Spread unknown fields from the existing plan first, so a PUT that does
  // not mention them preserves them. Then apply the caller's validated
  // overrides; only the four whitelisted fields are allowed.
  const merged: PersistedAnnotationPlan = {
    ...(existing ?? {}),
    kind: "annotation-plan",
    workspaceId,
    screenshotId,
    version: nextVersion,
    updatedAt: nowIso,
    updatedBy: session.userId,
  };

  // Apply each optional field. We intentionally do not use `??=` — an
  // explicit `overlays: []` in the body must overwrite (clear the list), and
  // `hasOwnProperty` was already enforced by `validatePutBody`.
  const withUpdates: PersistedAnnotationPlan = {
    ...merged,
    ...(Object.prototype.hasOwnProperty.call(validated, "overlays")
      ? { overlays: validated.overlays ?? [] }
      : {}),
    ...(Object.prototype.hasOwnProperty.call(validated, "stepCopy")
      ? { stepCopy: validated.stepCopy }
      : {}),
    ...(Object.prototype.hasOwnProperty.call(validated, "altText")
      ? { altText: validated.altText }
      : {}),
    ...(Object.prototype.hasOwnProperty.call(validated, "targetBox")
      ? { targetBox: validated.targetBox }
      : {}),
  };

  // ------------------------------------------------------------ persist ----
  const key = annotationKey(screenshotId);
  const serialized = JSON.stringify(withUpdates, null, 2);
  const bytes = Buffer.from(serialized, "utf8");
  const contentHash = createHash("sha256").update(bytes).digest("hex");

  try {
    await store.put(key, bytes, {
      contentType: "application/json",
      contentLength: bytes.length,
      metadata: {
        "zipy-kind": "annotation-plan",
        "zipy-screenshot-id": screenshotId,
        "zipy-content-hash": contentHash,
        "zipy-version": String(nextVersion),
      },
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(
      `[/api/annotations/[id]] storage write failed for ${screenshotId}: ${message}\n`,
    );
    return NextResponse.json(
      {
        error: "storage_failed",
        message:
          "The annotation plan could not be persisted. The update was not applied; retry the request.",
      },
      { status: 503 },
    );
  }

  const annotation = buildAnnotationDto(withUpdates);
  const response: AnnotationResponse = {
    screenshotId,
    workspaceId,
    state: "ready",
    version: nextVersion,
    annotation,
    updatedAt: nowIso,
    updatedBy: session.userId,
    message: `Annotation plan saved at version ${nextVersion}.`,
    notes: buildNotes(withUpdates),
  };
  return NextResponse.json(response, { status: 200 });
}

