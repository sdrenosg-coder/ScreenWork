import { useState, type ReactNode } from "react";
import { Link, useLocation } from "wouter";
import { LayoutDashboard, BarChart3, Palette, ShieldCheck, ListChecks, LogOut, LogIn, Menu, X, Zap } from "lucide-react";
import { useSession } from "../lib/session";
import Welcome from "../components/Welcome";

const NAV = [
  { href: "/dashboard", label: "Guides", icon: LayoutDashboard, id: "dashboard" },
  { href: "/analytics", label: "Analytics", icon: BarChart3, id: "analytics" },
  { href: "/settings/branding", label: "Branding", icon: Palette, id: "branding" },
  { href: "/admin", label: "Administration", icon: ShieldCheck, id: "admin" },
  { href: "/features", label: "Feature inventory", icon: ListChecks, id: "features" },
];

export default function RootLayout({ children }: { children: ReactNode }) {
  const [loc] = useLocation();
  const { state, logout } = useSession();
  const [open, setOpen] = useState(false);
  const [logoutError, setLogoutError] = useState("");

  if (loc === "/login" || loc === "/signup") return <>{children}</>;

  if (loc.startsWith("/p/")) {
    return (
      <div>
        <a className="z-skip" href="#zipy-main">Skip to main content</a>
        <div className="z-reader-top">
          <Link href="/dashboard" className="z-display" style={{ fontWeight: 700, fontSize: 20, textDecoration: "none", color: "var(--teal-d)" }}>Zipy</Link>
          <span style={{ fontSize: 12, color: "var(--muted)" }}>Published guide</span>
        </div>
        <main id="zipy-main" className="z-reader">{children}</main>
        <div className="z-foot">Content generated by Zipy AI is AI-generated unless a human reviewer has approved it.</div>
      </div>
    );
  }

  if (loc !== "/features" && state.status === "anon") return <Welcome />;
  if (loc !== "/features" && state.status === "loading") {
    return <main id="zipy-main" className="z-reader" aria-busy="true"><h1>Loading your workspace…</h1></main>;
  }

  const isActive = (h: string) => (h === "/dashboard" ? loc === "/" || loc === "/dashboard" : loc.startsWith(h));
  return (
    <div className="z-shell">
      <a className="z-skip" href="#zipy-main">Skip to main content</a>
      <aside className={"z-side" + (open ? " open" : "")} aria-label="Primary">
        <Link href="/dashboard" className="z-brand"><span className="z-mark"><Zap size={17} aria-hidden /></span>Zipy</Link>
        <nav className="z-nav" aria-label="Main navigation">
          <span className="z-navlabel">Workspace</span>
          {NAV.map((n) => (
            <Link key={n.href} href={n.href} data-testid={`link-nav-${n.id}`} aria-current={isActive(n.href) ? "page" : undefined} onClick={() => setOpen(false)}>
              <n.icon size={17} aria-hidden />{n.label}
            </Link>
          ))}
        </nav>
        <div className="z-user">
          {state.status === "authed" ? (
            <>
              <span data-testid="text-session-role">Signed in · {state.session.role}</span>
              <button type="button" className="z-btn z-btn-ghost" data-testid="button-logout" onClick={() => {
                setLogoutError("");
                void logout().catch(error => setLogoutError(error instanceof Error ? error.message : "Please try again."));
              }}><LogOut size={16} aria-hidden />Sign out</button>
              {logoutError && <p role="alert">{logoutError}</p>}
            </>
          ) : state.status === "loading" ? (
            <span>Checking session...</span>
          ) : (
            <>
              <span data-testid="text-session-anon">{state.status === "error" ? "Session unavailable" : "Not signed in"}</span>
              <Link href="/login" className="z-btn z-btn-ghost" data-testid="link-login"><LogIn size={16} aria-hidden />Sign in</Link>
            </>
          )}
        </div>
      </aside>
      <div className="z-body">
        <div className="z-top">
          <span className="z-display" style={{ fontWeight: 700, fontSize: 20 }}>Zipy</span>
          <button type="button" className="z-btn z-btn-ghost" aria-expanded={open} aria-label="Toggle navigation" data-testid="button-menu" onClick={() => setOpen(!open)}>{open ? <X size={18} /> : <Menu size={18} />}</button>
        </div>
        <main id="zipy-main" className="z-main">{children}</main>
        <footer className="z-foot">Content generated by Zipy AI is AI-generated unless a human reviewer has approved it.</footer>
      </div>
    </div>
  );
}
