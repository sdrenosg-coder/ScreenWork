/**
 * The surfaces the platform can render a guide into. Each has different
 * constraints on what the label can look like and whether it can be shown at
 * all. Keeping this list closed means the export layer can switch on it and
 * the regression suite can iterate it.
 */
export const DISCLOSURE_SURFACES = [
  "web-page",       // the hosted guide (/p/:slug and custom domain)
  "embed",          // iframe / JS snippet embedded in a third-party page
  "pdf",            // PDF export
  "docx",           // DOCX export
  "html-export",    // standalone HTML export
  "markdown",       // Markdown export
  "email",          // email announcement body
  "social-post",    // short social post
  "chatbot-response", // Q&A pair for a support chatbot
] as const;
export type DisclosureSurface = (typeof DISCLOSURE_SURFACES)[number];

/**
 * How prominent the label must be on the surface. `inline` means the label
 * is a sentence in the body; `badge` means a small pill rendered next to the
 * title; `footer` means a sentence at the bottom; `metadata-only` means the
 * surface cannot carry visible text (e.g. a JSON-LD-only consumer) and the
 * signal is machine-readable.
 */
export const DISCLOSURE_PROMINENCES = [
  "inline",
  "badge",
  "footer",
  "metadata-only",
] as const;
export type DisclosureProminence = (typeof DISCLOSURE_PROMINENCES)[number];

/** The audience the label targets. Different audiences need different wording. */
export const DISCLOSURE_AUDIENCES = [
  "reader",          // the end reader of the guide
  "reviewer",        // a human reviewer deciding whether to publish
  "crawler",         // machine-readable metadata for search engines
  "platform-review", // the receiving platform (social, marketplace)
] as const;
export type DisclosureAudience = (typeof DISCLOSURE_AUDIENCES)[number];

/**
 * The categories of signal. A visible label is one; the machine-readable
 * signals are others. Kept as an enum so the export layer can verify it
 * placed every required signal.
 */
export const DISCLOSURE_SIGNAL_KINDS = [
  "visible-label",           // text a reader sees
  "html-meta",               // <meta name="ai-generated" ...> and friends
  "json-ld",                 // Schema.org disambiguatingDescription / creator
  "markdown-attribute",      // a Markdown-visible footer line
  "email-footer",            // a footer line for email
  "data-attribute",          // data-ai-generated on the container element
  "http-header-hint",        // a header the serving layer may set
] as const;
export type DisclosureSignalKind = (typeof DISCLOSURE_SIGNAL_KINDS)[number];

/**
 * The catalogue entry for one label. `render` returns `null` when the context
 * is insufficient; the caller records a skip rather than emitting a sentinel.
 * `templateVersion` is a string so a data-only version bump does not require
 * a code change, and a `checkDisclosureCatalogueDrift` pass can compare a
 * previously-rendered payload against today's catalogue.
 */
export interface DisclosureCatalogueEntry {
  readonly templateId: string;
  readonly templateVersion: string;
  readonly signalKind: DisclosureSignalKind;
  readonly surface: DisclosureSurface;
  readonly prominence: DisclosureProminence;
  readonly audience: DisclosureAudience;
  readonly render: (ctx: DisclosureContext) => string | null;
}

export interface DisclosureContext {
  /** Legal name of the publisher. `null` when the operator has not supplied one. */
  readonly publisherLegalName: string | null;
  /** Public product name shown to readers (e.g. "Acme Cloud"). */
  readonly productName: string | null;
  /** Public link the reader can follow to learn about the platform. */
  readonly learnMoreUrl: string;
  /** Human-readable ISO 8601 timestamp the label was produced. */
  readonly generatedAt: string;
  /** The model family that wrote the prose, when the deployment records it. */
  readonly modelLabel: string | null;
  /** True when a human reviewer has approved the published version. */
  readonly humanReviewed: boolean;
  /** True when the guide is currently a draft not yet reviewed. */
  readonly draft: boolean;
  /** Surface being rendered. */
  readonly surface: DisclosureSurface;
  /** Target audience for the label. */
  readonly audience: DisclosureAudience;
  /** The guide's own industry. Used for which long-form is legal-defensible. */
  readonly industry: IndustryProfile;
  /** The guide's audience profile. Used for tone. */
  readonly readerAudience: AudienceProfile;
}

export interface DisclosureLabel {
  readonly templateId: string;
  readonly templateVersion: string;
  readonly signalKind: DisclosureSignalKind;
  readonly surface: DisclosureSurface;
  readonly prominence: DisclosureProminence;
  readonly audience: DisclosureAudience;
  /** Fully rendered text with all variables resolved. */
  readonly text: string;
}

export interface DisclosureSkip {
  readonly surface: DisclosureSurface;
  readonly signalKind: DisclosureSignalKind;
  readonly reason: string;
}

export interface DisclosureNote {
  readonly kind:
    | "surface-cannot-carry-visible-label"
    | "human-reviewed"
    | "draft-guide"
    | "model-not-recorded"
    | "publisher-not-supplied"
    | "industry-guidance"
    | "catalogue-unmatched"
    | "regulatory-frameworks-referenced"
    | "duplicate-signal-collapsed";
  readonly detail: string;
}

export interface Disclosure {
  readonly version: "disclosure/1";
  readonly surface: DisclosureSurface;
  readonly labels: readonly DisclosureLabel[];
  /**
   * The primary visible label for this surface, when the surface carries one.
   * `null` for `metadata-only` surfaces. The export layer uses this when it
   * needs a single string (e.g. the `<figcaption>` on a PDF cover).
   */
  readonly primaryLabel: DisclosureLabel | null;
  readonly skipped: readonly DisclosureSkip[];
  readonly notes: readonly DisclosureNote[];
  readonly summary: {
    readonly total: number;
    readonly visible: number;
    readonly machine: number;
    readonly skipped: number;
    readonly humanReviewed: boolean;
    readonly draft: boolean;
  };
  /**
   * True when the surface carries a visible label. A deployment that exposes
   * the guide publicly with `visible: false` on a surface that is legally
   * required to carry one must be investigated — the export regression suite
   * asserts this.
   */
  readonly hasVisibleLabel: boolean;
  readonly generatedAt: string;
  readonly aiGenerated: true;
}

export interface BuildDisclosureInput {
  readonly surface: DisclosureSurface;
  readonly publisherLegalName?: string | null;
  readonly productName?: string | null;
  readonly learnMoreUrl?: string | null;
  readonly modelLabel?: string | null;
  readonly humanReviewed?: boolean;
  readonly draft?: boolean;
  readonly industry: IndustryProfile;
  readonly audience: AudienceProfile;
}

