export function buildDisclosure(input: BuildDisclosureInput): Disclosure {
  if (input === null || typeof input !== "object") {
    throw new DisclosureError("buildDisclosure requires an input object.", "invalid-input");
  }
  if (
    typeof input.surface !== "string" ||
    !(DISCLOSURE_SURFACES as readonly string[]).includes(input.surface)
  ) {
    throw new DisclosureError(
      `\`surface\` must be one of ${DISCLOSURE_SURFACES.join(", ")}.`,
      "invalid-input",
    );
  }
  if (input.industry === null || typeof input.industry !== "object") {
    throw new DisclosureError("`industry` is required.", "invalid-input");
  }
  if (input.audience === null || typeof input.audience !== "object") {
    throw new DisclosureError("`audience` is required.", "invalid-input");
  }

  const notes: DisclosureNote[] = [];

  const context: DisclosureContext = {
    publisherLegalName: readNonEmptyString(input.publisherLegalName),
    productName: readNonEmptyString(input.productName),
    learnMoreUrl:
      readNonEmptyString(input.learnMoreUrl) ??
      "https://zipy.ai/about/ai-generated-content",
    generatedAt: new Date().toISOString(),
    modelLabel: readNonEmptyString(input.modelLabel),
    humanReviewed: input.humanReviewed === true,
    draft: input.draft === true,
    surface: input.surface,
    audience: "reader",
    industry: input.industry,
    readerAudience: input.audience,
  };

  if (context.publisherLegalName === null) {
    notes.push({
      kind: "publisher-not-supplied",
      detail:
        "No publisher legal name was supplied; the label falls back to the generic publisher reference.",
    });
  }
  if (context.modelLabel === null) {
    notes.push({
      kind: "model-not-recorded",
      detail:
        "The model that wrote the guide was not recorded; the visible label omits the model name.",
    });
  }
  if (context.humanReviewed) {
    notes.push({
      kind: "human-reviewed",
      detail:
        "The guide is marked as human-reviewed; the label says so explicitly so a reader can distinguish a reviewed guide from an unreviewed one.",
    });
  }
  if (context.draft) {
    notes.push({
      kind: "draft-guide",
      detail: "The guide is a draft; the label states that it has not been approved for publication.",
    });
  }

  // Industry-specific note. Health/finance/legal readers receive an additional
  // cue in the label so that the guide is not mistaken for a first-party
  // product statement; the note records the reason for the extra cue.
  const industryKeys = normaliseIndustryKeys(input.industry);
  if (
    industryKeys.some((k) =>
      ["health", "medical", "clinic", "pharma", "care", "financ", "bank", "insurance", "legal", "law"].some(
        (h) => k.includes(h),
      ),
    )
  ) {
    notes.push({
      kind: "industry-guidance",
      detail:
        "The guide's industry is regulated or advisory-sensitive; the visible label retains the publisher reference even when the deployment has not supplied one.",
    });
  }
  if (
    industryKeys.some((k) => REGULATED_FRAMEWORK_HINTS.some((h) => k.includes(h)))
  ) {
    notes.push({
      kind: "regulatory-frameworks-referenced",
      detail:
        "The industry profile references a regulatory framework. The label is a disclosure of provenance only and does not assert compliance with that framework.",
    });
  }

  const relevant = DEFAULT_DISCLOSURE_CATALOGUE.filter(
    (entry) => entry.surface === input.surface,
  );

  const labels: DisclosureLabel[] = [];
  const skipped: DisclosureSkip[] = [];

  for (const entry of relevant) {
    // The catalogue entry's audience is a targeting hint; the caller's
    // audience is a *selection* filter applied by the surface. Reader-facing
    // audiences all get the reader-facing label; the crawler signals are
    // always emitted for surfaces that support them.
    const text = entry.render(context);
    if (text === null || text.trim().length === 0) {
      skipped.push({
        surface: entry.surface,
        signalKind: entry.signalKind,
        reason: `Template "${entry.templateId}" could not be rendered with the supplied context.`,
      });
      continue;
    }
    labels.push({
      templateId: entry.templateId,
      templateVersion: entry.templateVersion,
      signalKind: entry.signalKind,
      surface: entry.surface,
      prominence: entry.prominence,
      audience: entry.audience,
      text: text.trim(),
    });
  }

  // Detect a required signal kind for which no catalogue entry exists. This is
  // a data gap, not a style choice; it is recorded so an operator sees the
  // catalogue hole.
  const requiredSignalKindsForSurface = requiredSignalKinds(input.surface);
  const provided = new Set(labels.map((l) => l.signalKind));
  for (const kind of requiredSignalKindsForSurface) {
    if (!provided.has(kind)) {
      notes.push({
        kind: "catalogue-unmatched",
        detail: `Signal kind "${kind}" is required for surface "${input.surface}" but no template produced it.`,
      });
    }
  }

  // Visible-label requirement check.
  const hasVisibleLabel = labels.some((l) => l.signalKind === "visible-label");
  if (
    !hasVisibleLabel &&
    (SURFACES_REQUIRING_VISIBLE_LABEL as readonly string[]).includes(input.surface)
  ) {
    notes.push({
      kind: "surface-cannot-carry-visible-label",
      detail: `Surface "${input.surface}" requires a visible disclosure label but none could be rendered.`,
    });
  }

  const primaryLabel =
    labels.find((l) => l.signalKind === "visible-label" && l.prominence === "inline") ??
    labels.find((l) => l.signalKind === "visible-label") ??
    null;

  const visible = labels.filter(
    (l) => l.signalKind === "visible-label" || l.signalKind === "email-footer" || l.signalKind === "markdown-attribute",
  ).length;
  const machine = labels.length - visible;

  return {
    version: "disclosure/1",
    surface: input.surface,
    labels,
    primaryLabel,
    skipped,
    notes,
    summary: {
      total: labels.length,
      visible,
      machine,
      skipped: skipped.length,
      humanReviewed: context.humanReviewed,
      draft: context.draft,
    },
    hasVisibleLabel,
    generatedAt: context.generatedAt,
    aiGenerated: true,
  };
}

/**
 * Render the disclosure as HTML. Returns a fragment whose components the
 * export layer places:
 *   - `<meta>` tags the caller injects in `<head>`;
 *   - a `<section class="zipy-ai-disclosure">` block for the body.
 *
 * The two are returned together so a caller that only wants one still has it
 * available and no caller has to know which template produced which.
 */
export function renderDisclosureHtml(disclosure: Disclosure): {
  readonly headTags: string;
  readonly body: string;
} {
  if (
    disclosure === null ||
    typeof disclosure !== "object" ||
    disclosure.version !== "disclosure/1"
  ) {
    throw new DisclosureError(
      'renderDisclosureHtml requires a Disclosure object (version "disclosure/1").',
      "invalid-input",
    );
  }
  const metaTags: string[] = [];
  const attrFragments: string[] = [];
  const bodyParagraphs: string[] = [];
  let jsonLdBlock = "";

  for (const label of disclosure.labels) {
    switch (label.signalKind) {
      case "html-meta": {
        // The template packs a `k="v"|k="v"` list; unpack it into <meta> tags.
        const pairs = label.text.split("|").map((s) => s.trim()).filter(Boolean);
        for (const pair of pairs) {
          const eq = pair.indexOf("=");
          if (eq < 0) continue;
          const key = pair.slice(0, eq).trim();
          const value = pair.slice(eq + 1).trim();
          metaTags.push(`<meta ${key} ${value} />`);
        }
        break;
      }
      case "json-ld": {
        // Only the first JSON-LD block is emitted; a second would produce
        // duplicate structured data on the page.
        if (jsonLdBlock.length === 0) {
          jsonLdBlock = `<script type="application/ld+json">${label.text}</script>`;
        }
        break;
      }
      case "data-attribute": {
        attrFragments.push(label.text);
        break;
      }
      case "visible-label":
      case "email-footer":
      case "markdown-attribute": {
        const tag =
          label.prominence === "badge"
            ? "span"
            : "p";
        const klass =
          label.prominence === "badge"
            ? "zipy-ai-badge"
            : "zipy-ai-disclosure-line";
        bodyParagraphs.push(
          `<${tag} class="${klass}" data-ai-label-template="${escapeHtmlAttr(
            label.templateId,
          )}" data-ai-label-version="${escapeHtmlAttr(label.templateVersion)}">${escapeHtmlText(
            label.text,
          )}</${tag}>`,
        );
        break;
      }
      default:
        break;
    }
  }

  const headTags = [...metaTags, jsonLdBlock].filter((s) => s.length > 0).join("\n");

  const bodyLines: string[] = [];
  if (bodyParagraphs.length > 0 || attrFragments.length > 0) {
    bodyLines.push(
      `<section class="zipy-ai-disclosure" ${attrFragments.join(" ")} data-surface="${escapeHtmlAttr(
        disclosure.surface,
      )}">`,
    );
    for (const p of bodyParagraphs) bodyLines.push(`  ${p}`);
    bodyLines.push("</section>");
  }

  return { headTags, body: bodyLines.join("\n") };
}

/**
 * Render the disclosure as a Markdown block. Any html-meta/json-ld label is
 * emitted as an HTML comment because Markdown has no metadata field; the
 * export layer is expected to fold those into the surrounding document's own
 * front matter if it wants them machine-readable.
 */
export function renderDisclosureMarkdown(disclosure: Disclosure): string {
  if (
    disclosure === null ||
    typeof disclosure !== "object" ||
    disclosure.version !== "disclosure/1"
  ) {
    throw new DisclosureError(
      'renderDisclosureMarkdown requires a Disclosure object (version "disclosure/1").',
      "invalid-input",
    );
  }
  const lines: string[] = [];
  for (const label of disclosure.labels) {
    switch (label.signalKind) {
      case "visible-label":
        lines.push(label.text);
        lines.push("");
        break;
      case "markdown-attribute":
        lines.push(label.text);
        lines.push("");
        break;
      case "html-meta":
        lines.push(`<!-- ai-disclosure-meta: ${label.text} -->`);
        break;
      case "json-ld":
        lines.push("<!-- ai-disclosure-jsonld: included as <script type=\"application/ld+json\"> in the HTML variant -->");
        break;
      default:
        break;
    }
  }
  while (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
  return lines.join("\n");
}

/**
 * Render the disclosure as a plain-text block. Used for email bodies whose
 * template has no HTML part, SMS notifications, and plain-text log lines in
 * the audit trail.
 */
export function renderDisclosurePlain(disclosure: Disclosure): string {
  if (
    disclosure === null ||
    typeof disclosure !== "object" ||
    disclosure.version !== "disclosure/1"
  ) {
    throw new DisclosureError(
      'renderDisclosurePlain requires a Disclosure object (version "disclosure/1").',
      "invalid-input",
    );
  }
  const lines: string[] = [];
  for (const label of disclosure.labels) {
    switch (label.signalKind) {
      case "visible-label":
      case "email-footer":
        lines.push(label.text);
        break;
      case "markdown-attribute":
        // Strip the HTML comment for plain text; the visible line follows.
        for (const sub of label.text.split("\n")) {
          if (sub.startsWith("<!--")) continue;
          lines.push(sub);
        }
        break;
      default:
        // Machine-readable signals do not appear in plain text.
        break;
    }
  }
  return lines.join("\n");
}

/**
 * The LLM-visible directive block. Append to the writer's system prompt. The
 * writer must not write the label; it must leave room and must not contradict
 * what the label states.
 */
export function buildDisclosureDirectives(input: {
  readonly surface: DisclosureSurface;
  readonly audience: AudienceProfile;
  readonly humanReviewed: boolean;
}): string {
  const lines: string[] = [];
  lines.push(
    "The published guide will carry an AI-generated disclosure rendered from a template catalogue. Do not write the disclosure yourself, and do not claim the guide is human-written.",
  );
  lines.push(
    "- Do not open with \"As an AI…\" or a similar meta-statement. The disclosure is separate and consistently placed.",
  );
  lines.push(
    "- Do not assert that the guide has been reviewed by a human. Whether it has is decided by the review phase and reflected in the label; a claim of review in the body would contradict the label.",
  );
  lines.push(
    "- Do not state a certification, licence or date that the label does not carry. If the label's version has to change, the reviewer changes the catalogue, not the prose.",
  );
  if (input.surface === "social-post") {
    lines.push(
      "- The summary will be published on a social platform. The visible marker `[AI-generated]` is placed by the publishing layer; begin your summary with the reader-facing content, not with the marker.",
    );
  }
  if (input.surface === "email") {
    lines.push(
      "- The email footer carries the disclosure. Do not repeat it in the body; a reader does not need to be told twice.",
    );
  }
  if (input.audience.seniority === "novice") {
    lines.push(
      "- A novice reader may not connect the label to the guide's provenance. Be factual about what the guide does and does not do; do not add reassurance the label does not support.",
    );
  }
  if (!input.humanReviewed) {
    lines.push(
      "- This guide has not yet been reviewed. Write conservatively: prefer omitting an assertion over making one the sources do not support.",
    );
  }
  return lines.join("\n");
}

/**
 * Check whether a *rendered* artefact carries the disclosure. The export
 * regression suite calls this with the produced HTML/Markdown/text and the
 * `Disclosure` that produced it, and asserts that every visible-label
 * template id appears in the output. The check is a substring match on the
 * template's rendered text plus the template id marker in HTML; a template
 * that gets dropped by a bad export path fails the check rather than shipping
 * silently.
 */
export function disclosurePresentIn(
  disclosure: Disclosure,
  rendered: string,
): {
  readonly ok: boolean;
  readonly missing: readonly { readonly templateId: string; readonly signalKind: DisclosureSignalKind }[];
} {
  if (disclosure === null || typeof disclosure !== "object" || disclosure.version !== "disclosure/1") {
    throw new DisclosureError(
      'disclosurePresentIn requires a Disclosure object (version "disclosure/1").',
      "invalid-input",
    );
  }
  if (typeof rendered !== "string") {
    throw new DisclosureError("`rendered` must be a string.", "invalid-input");
  }
  const missing: { templateId: string; signalKind: DisclosureSignalKind }[] = [];
  for (const label of disclosure.labels) {
    if (label.signalKind === "html-meta" || label.signalKind === "json-ld") {
      // Machine signals are present iff their content appears; some export
      // paths intentionally defer them to front matter, so their absence is
      // not an error here. The suite checks those separately per surface.
      continue;
    }
    // A visible label passes when either its exact rendered text or its
    // template id appears. The template id is checked because a rendering
    // may legitimately substitute the label text with an image of it.
    if (!rendered.includes(label.text) && !rendered.includes(label.templateId)) {
      missing.push({ templateId: label.templateId, signalKind: label.signalKind });
    }
  }
  return { ok: missing.length === 0, missing };
}

export function rehydrateDisclosure(value: unknown): Disclosure {
  if (value === null || typeof value !== "object") {
    throw new DisclosureError("Rehydrate failed: payload is not an object.", "shape");
  }
  const r = value as Record<string, unknown>;
  if (r["version"] !== "disclosure/1") {
    throw new DisclosureError(
      `Rehydrate failed: expected version "disclosure/1", received "${String(r["version"])}".`,
      "shape",
    );
  }
  const surfaceRaw = r["surface"];
  const surface: DisclosureSurface =
    typeof surfaceRaw === "string" && (DISCLOSURE_SURFACES as readonly string[]).includes(surfaceRaw)
      ? (surfaceRaw as DisclosureSurface)
      : "web-page";
  return {
    version: "disclosure/1",
    surface,
    labels: readLabels(r["labels"]),
    primaryLabel: readPrimaryLabel(r["primaryLabel"]),
    skipped: readSkips(r["skipped"]),
    notes: readNotes(r["notes"]),
    summary: readSummary(r["summary"]),
    hasVisibleLabel: r["hasVisibleLabel"] === true,
    generatedAt: typeof r["generatedAt"] === "string" ? r["generatedAt"] : "",
    aiGenerated: true,
  };
}

/**
 * Validate that every label in a persisted disclosure points at a catalogue
 * entry whose `templateVersion` still matches what the catalogue declares.
 * Returns the drifting pairs so a legal-review screen can flag a guide whose
 * label was rendered against an out-of-date wording.
 */
export function checkDisclosureCatalogueDrift(
  disclosure: Disclosure,
  catalogue: readonly DisclosureCatalogueEntry[] = DEFAULT_DISCLOSURE_CATALOGUE,
): readonly { readonly templateId: string; readonly rendered: string; readonly current: string }[] {
  const current = new Map(catalogue.map((e) => [e.templateId, e.templateVersion]));
  const out: { templateId: string; rendered: string; current: string }[] = [];
  for (const l of disclosure.labels) {
    const cur = current.get(l.templateId);
    if (cur === undefined) continue;
    if (cur !== l.templateVersion) {
      out.push({ templateId: l.templateId, rendered: l.templateVersion, current: cur });
    }
  }
  return out;
}

