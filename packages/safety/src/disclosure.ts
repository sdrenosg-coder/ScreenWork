/**
 * Zipy AI — AI disclosure labels (SEO/quality/safety phase, batch 4).
 *
 * The final safety-phase module. It produces the *visible* AI-generated
 * disclosure the guide carries wherever it is published (guide page, PDF,
 * DOCX, HTML, Markdown, embed, email, social card, JSON-LD), and the
 * machine-readable signals that let a crawler, a social platform and an
 * accessibility tool detect the same fact programmatically.
 *
 * Why a dedicated module rather than a sentence in the writer prompt:
 *   - Regulations and platform policies (EU AI Act transparency, Google
 *     Search's AI-content guidance, Meta/YouTube disclosure requirements,
 *     several US state laws) require the *publisher* to disclose, not just
 *     the writer, and the disclosure has to appear on every rendering of the
 *     content, not only on the platform's own page.
 *   - The label must be stable text an operator can cite, and its presence
 *     must be *provable*: each export path must be able to answer "does this
 *     artefact carry the required disclosure?"
 *   - The label must interact with the disclaimers layer without duplicating
 *     it: `@zipy/safety/disclaimers` owns the *legal* framing
 *     ("…does not claim the guide is free of inaccuracies"); this module owns
 *     the *provenance* framing ("…was generated by Zipy AI from the sources
 *     the author provided"), so a reader can tell the two apart and a
 *     legal reviewer knows which one to edit.
 *
 * Design rules honoured (consistent with the other modules in this phase):
 *  - Deterministic given inputs. Same input → same labels, same order.
 *  - No placeholders emitted at render time. A label whose catalogue template
 *    requires a variable the deployment has not supplied is *skipped* and the
 *    skip is recorded, rather than emitting a `{{...}}` sentinel.
 *  - No model call. The label text comes from a versioned, reviewable
 *    catalogue. The LLM is instructed (via `buildDisclosureDirectives`) to
 *    leave room for it but never to write it.
 *  - No compliance claim. The module reports what *it* produced and why; it
 *    does not assert that the deployment is compliant with any framework.
 *    Actual compliance depends on the operator publishing the label according
 *    to the surface's requirements, which this module cannot verify.
 *  - No silent omissions. Every placement the platform supports produces an
 *    entry in the result — either a `DisclosureLabel` or a
 *    `DisclosureSkip` naming the reason. A surface that cannot render the
 *    label (e.g. a 280-char social card) is recorded as such so the
 *    publishing layer can decide whether to shorten, omit the guide, or route
 *    the summary to a text-only channel.
 *  - Machine-readable signals are *separate* from the visible label. The
 *    HTML `<meta>`, the JSON-LD `disambiguatingDescription`, the
 *    `ai-generated` data attribute, and the `X-Robots-Tag`-adjacent hints are
 *    all returned as distinct fields the export layer can place precisely.
 *
 * The module exports:
 *   - `buildDisclosure` — the primary entry point.
 *   - `renderDisclosureHtml` — an export-ready HTML fragment + meta tags.
 *   - `renderDisclosureMarkdown` — an export-ready Markdown block.
 *   - `renderDisclosurePlain` — an export-ready plain-text block (email body,
 *     plain-text fallback).
 *   - `buildDisclosureDirectives` — the LLM-visible block.
 *   - `disclosurePresentIn` — check whether a rendered artefact carries the
 *     required disclosure (used by the export regression suite).
 *   - `rehydrateDisclosure` — typed load of a persisted payload.
 *   - `__internals` — catalogue and helpers, exported for tests.
 */

