function requiredSignalKinds(surface: DisclosureSurface): readonly DisclosureSignalKind[] {
  switch (surface) {
    case "web-page":
      return ["visible-label", "html-meta", "json-ld", "data-attribute"];
    case "embed":
      return ["visible-label", "data-attribute"];
    case "pdf":
      return ["visible-label"];
    case "docx":
      return ["visible-label"];
    case "html-export":
      return ["visible-label", "html-meta", "json-ld"];
    case "markdown":
      return ["markdown-attribute"];
    case "email":
      return ["email-footer"];
    case "social-post":
      return ["visible-label"];
    case "chatbot-response":
      return ["visible-label"];
    default:
      return [];
  }
}

function readNonEmptyString(v: unknown): string | null {
  if (typeof v !== "string") return null;
  const t = v.trim();
  return t.length > 0 ? t : null;
}

function normaliseIndustryKeys(industry: IndustryProfile): readonly string[] {
  const keys: string[] = [];
  const pushIfString = (v: unknown): void => {
    if (typeof v === "string" && v.trim().length > 0) keys.push(v.trim().toLowerCase());
  };
  const obj = industry as unknown as Record<string, unknown>;
  pushIfString(obj["id"]);
  pushIfString(obj["name"]);
  pushIfString(obj["label"]);
  pushIfString(obj["industry"]);
  if (Array.isArray(obj["tags"])) {
    for (const t of obj["tags"]) pushIfString(t);
  }
  return keys;
}

function escapeHtmlText(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function escapeHtmlAttr(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/** Alias used inside template renders where only attribute escaping matters. */
const escapeAttr = escapeHtmlAttr;

function readSignalKind(v: unknown): DisclosureSignalKind {
  return typeof v === "string" && (DISCLOSURE_SIGNAL_KINDS as readonly string[]).includes(v)
    ? (v as DisclosureSignalKind)
    : "visible-label";
}

function readProminence(v: unknown): DisclosureProminence {
  return typeof v === "string" && (DISCLOSURE_PROMINENCES as readonly string[]).includes(v)
    ? (v as DisclosureProminence)
    : "inline";
}

function readAudience(v: unknown): DisclosureAudience {
  return typeof v === "string" && (DISCLOSURE_AUDIENCES as readonly string[]).includes(v)
    ? (v as DisclosureAudience)
    : "reader";
}

function readLabels(v: unknown): readonly DisclosureLabel[] {
  if (!Array.isArray(v)) return [];
  const out: DisclosureLabel[] = [];
  for (const item of v) {
    if (item === null || typeof item !== "object") continue;
    const o = item as Record<string, unknown>;
    const surfaceRaw = o["surface"];
    const surface: DisclosureSurface =
      typeof surfaceRaw === "string" && (DISCLOSURE_SURFACES as readonly string[]).includes(surfaceRaw)
        ? (surfaceRaw as DisclosureSurface)
        : "web-page";
    out.push({
      templateId: typeof o["templateId"] === "string" ? o["templateId"] : "",
      templateVersion: typeof o["templateVersion"] === "string" ? o["templateVersion"] : "",
      signalKind: readSignalKind(o["signalKind"]),
      surface,
      prominence: readProminence(o["prominence"]),
      audience: readAudience(o["audience"]),
      text: typeof o["text"] === "string" ? o["text"] : "",
    });
  }
  return out;
}

function readPrimaryLabel(v: unknown): DisclosureLabel | null {
  if (v === null || typeof v !== "object") return null;
  const arr = readLabels([v]);
  return arr[0] ?? null;
}

function readSkips(v: unknown): readonly DisclosureSkip[] {
  if (!Array.isArray(v)) return [];
  const out: DisclosureSkip[] = [];
  for (const item of v) {
    if (item === null || typeof item !== "object") continue;
    const o = item as Record<string, unknown>;
    const surfaceRaw = o["surface"];
    const surface: DisclosureSurface =
      typeof surfaceRaw === "string" && (DISCLOSURE_SURFACES as readonly string[]).includes(surfaceRaw)
        ? (surfaceRaw as DisclosureSurface)
        : "web-page";
    out.push({
      surface,
      signalKind: readSignalKind(o["signalKind"]),
      reason: typeof o["reason"] === "string" ? o["reason"] : "",
    });
  }
  return out;
}

function readNotes(v: unknown): readonly DisclosureNote[] {
  if (!Array.isArray(v)) return [];
  const out: DisclosureNote[] = [];
  for (const item of v) {
    if (item === null || typeof item !== "object") continue;
    const o = item as Record<string, unknown>;
    const kind = o["kind"];
    if (
      kind !== "surface-cannot-carry-visible-label" &&
      kind !== "human-reviewed" &&
      kind !== "draft-guide" &&
      kind !== "model-not-recorded" &&
      kind !== "publisher-not-supplied" &&
      kind !== "industry-guidance" &&
      kind !== "catalogue-unmatched" &&
      kind !== "regulatory-frameworks-referenced" &&
      kind !== "duplicate-signal-collapsed"
    ) {
      continue;
    }
    out.push({ kind, detail: typeof o["detail"] === "string" ? o["detail"] : "" });
  }
  return out;
}

function readSummary(v: unknown): Disclosure["summary"] {
  const fallback: Disclosure["summary"] = {
    total: 0,
    visible: 0,
    machine: 0,
    skipped: 0,
    humanReviewed: false,
    draft: false,
  };
  if (v === null || typeof v !== "object") return fallback;
  const o = v as Record<string, unknown>;
  const read = (k: string): number => {
    const val = o[k];
    return typeof val === "number" && Number.isFinite(val) ? Math.max(0, Math.floor(val)) : 0;
  };
  return {
    total: read("total"),
    visible: read("visible"),
    machine: read("machine"),
    skipped: read("skipped"),
    humanReviewed: o["humanReviewed"] === true,
    draft: o["draft"] === true,
  };
}

